#pragma once
//----------------------------------------------------------------------------------------------------
#include <cstdint>

#include "Engine/Core/EventSystem.hpp"

//-Forward-Declaration--------------------------------------------------------------------------------
class Camera;
class Clock;
class Player;
class Prop;

//----------------------------------------------------------------------------------------------------
enum class eGameState : uint8_t
{
    ATTRACT,
    GAME
};

//----------------------------------------------------------------------------------------------------
class Game
{
public:
    //------------------------------------------------------------------------------------------------
    // Construct / Destruct
    //------------------------------------------------------------------------------------------------
    Game();
    ~Game();

    //------------------------------------------------------------------------------------------------
    // Life cycle
    //------------------------------------------------------------------------------------------------
    void Update();
    void Render() const;

    //------------------------------------------------------------------------------------------------
    // Game state
    //------------------------------------------------------------------------------------------------
    eGameState GetGameState() const;
    void       SetGameState(eGameState newState);
    bool       IsAttractState() const;
    bool       IsGameState() const;

private:
    //------------------------------------------------------------------------------------------------
    // Game state
    //------------------------------------------------------------------------------------------------
    static bool OnGameStateChanged(EventArgs& args);

    //------------------------------------------------------------------------------------------------
    // Update
    //------------------------------------------------------------------------------------------------
    void UpdateGame();
    void UpdateTime() const;
    void UpdateDebugDraw() const;
    void UpdateEntities(float gameDeltaSeconds, float systemDeltaSeconds) const;

    //------------------------------------------------------------------------------------------------
    // Render
    //------------------------------------------------------------------------------------------------
    void RenderAttract() const;
    void RenderGame() const;
    void RenderEntities() const;

    void SpawnPlayer();
    void SpawnProp();

    Camera*    m_screenCamera = nullptr;
    Player*    m_player       = nullptr;
    Prop*      m_firstCube    = nullptr;
    Prop*      m_secondCube   = nullptr;
    Prop*      m_sphere       = nullptr;
    Prop*      m_grid         = nullptr;
    Clock*     m_gameClock    = nullptr;
    eGameState m_gameState    = eGameState::ATTRACT;
};
